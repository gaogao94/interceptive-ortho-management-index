    out = sys.argv[1]

    wb = Workbook()
    wb.remove(wb.active)
    sheet_overview(wb)
    for dim in "ABCD":
        sheet_dimension(wb, dim)

    wb.save(out)
    print(f"已生成 {out}")
    print("工作表:", wb.sheetnames)
    return 0


